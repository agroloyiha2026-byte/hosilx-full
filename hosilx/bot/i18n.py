STRINGS = {lang: {k: v[i] for k, v in _S.items()} for i, lang in enumerate(LANGS)}

def has_key(key: str) -> bool:
    return key in _S


def tr(lang: str, key: str, **kw) -> str:
    """Matn (til bo'lmasa o'zbekcha, kalit bo'lmasa kalitning o'zi). {joy} to'ldirgichlar kw bilan."""
    s = STRINGS.get(lang, STRINGS["uz"]).get(key) or STRINGS["uz"].get(key) or key
    try:
        return s.format(**kw) if kw else s
    except (KeyError, IndexError):
        return s


